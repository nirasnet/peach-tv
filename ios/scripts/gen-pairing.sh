#!/bin/bash
# Writes PeachRemote/Generated/Pairing.generated.swift from tv-agent/.pairing.json (made by
# tv-agent/install.sh). The file is gitignored: it holds the TV's token.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
pairing="$here/../tv-agent/.pairing.json"
out="$here/PeachRemote/Generated/Pairing.generated.swift"
TS_HOST="${TS_HOST:-}"     # the TV's Tailscale 100.x address (optional)
LAN_HOST="${LAN_HOST:-}"   # the TV's home Wi-Fi address
token=""; port=8765
if [ -f "$pairing" ]; then
  token="$(python3 -c 'import json,sys;print(json.load(open(sys.argv[1]))["token"])' "$pairing")"
  port="$(python3 -c 'import json,sys;print(json.load(open(sys.argv[1])).get("port",8765))' "$pairing")"
else
  echo "warning: $pairing not found; the app will ask for the token in Settings" >&2
fi
mkdir -p "$(dirname "$out")"
cat > "$out" <<SWIFT
// Generated by scripts/gen-pairing.sh. Do not commit.
enum DefaultPairing {
    static let token = "$token"
    static let tailscaleHost = "$TS_HOST"
    static let lanHost = "$LAN_HOST"
    static let port = $port
}
SWIFT
echo "wrote $out"
